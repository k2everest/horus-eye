// Convert verifier-owned single-instance WiredAir configuration + a
// source-derived native geometry report into a canonical symbolic CMS
// transcript. This is NOT a byte-level transcript replay or proof of
// quantum commitment extraction. Reports supplied by provers are untrusted.
import {matchNativeHidingDegreeReport} from './hiding-degree-profile.mjs';
import {wiredRoundSchedule} from './round-state.mjs';
const fail=message=>{throw new TypeError(message);};
const integer=(v,a,b)=>Number.isSafeInteger(v)&&v>=a&&v<=b;
const freeze=Object.freeze;

/**
 * Requires a native report independently generated by the verifier's
 * pinned build, NEVER included in a prover's proof or accepted on its own
 * as cryptographic attestation.
 */
export function deriveWiredScheduleFromNativeReport(report,{
  expectedProgramSha512,
}={}){
  if(!report||typeof report!=='object'||Array.isArray(report))
    fail('NATIVE_WIRED_REPORT_REQUIRED');
  if(typeof expectedProgramSha512!=='string'||
    !/^[0-9a-f]{128}$/.test(expectedProgramSha512)||
    report.program_sha512!==expectedProgramSha512)
    fail('PROGRAM_DIGEST_NOT_VERIFIER_AUTHENTICATED');
  // The production native profile is single-instance, one LogUp bus and
  // zero grinding. No multi-height or unverified FRI schedule is accepted.
  if(report.num_lookups!==1||
    !integer(report.num_batched_functions,1,1_000_000)||
    report.hiding_fri!==true||
    report.fri_queries!==320)
    fail('UNSUPPORTED_WIRED_INSTANCE_OR_LOOKUP_SHAPE');
  const matched=matchNativeHidingDegreeReport(report);
  const rounds=matched.fri.rounds;
  if(rounds.length<1||rounds.length>32||
    !rounds.every(r=>r.log_arity===1&&
      integer(r.input_evaluation_rows,16,2**27)&&
      integer(r.merkle_leaf_rows,8,2**26)&&
      r.merkle_leaf_rows*2===r.input_evaluation_rows))
    fail('UNSUPPORTED_FRI_NATIVE_ROUNDS');
  const friLogArities=rounds.map(r=>r.log_arity);
  const schedule=wiredRoundSchedule({
    friLogArities, batchInstances:1,lookupInstances:1,
    friQueries:report.fri_queries,
    lookupPowBits:0,oodPowBits:0,
    pcsBatchPowBits:0,friCommitPowBits:0,friQueryPowBits:0,
    hasPreprocessed:true,hiding:true,
  });
  const friSteps=schedule.steps.filter(s=>s.id.startsWith('fri_commitment_'));
  if(friSteps.length!==rounds.length||
     schedule.parameters.friLogArities.some((a,i)=>a!==rounds[i].log_arity))
    fail('NATIVE_FRI_TRANSCRIPT_MISMATCH');
  return freeze({
    schema:'AEGIS_WIRED_NATIVE_REPORT_DERIVED_CMS_SCHEDULE_V1',
    program_sha512:expectedProgramSha512,
    schedule, matched_geometry:matched,
    fri_round_count:rounds.length,
    declared_initial_lde_rows:matched.fri.initial_lde_rows,
    declared_terminal_degree_exclusive:matched.fri.final_polynomial_degree_exclusive,
    // This checks the report against fixed code assumptions; it cannot
    // attest that the report was generated by an authenticated binary.
    derived_from_report_not_prover_arity:true,
    native_build_attested:false,
    rust_verifier_byte_transcript_equivalence_proved:false,
    arbitrary_prover_fri_query_projection_proved:false,
    cms_terminal_covering_executable_proved:false,
    quantum_vector_commitment_extraction_proved:false,
    pq128_demonstrated:false,production_ready:false,
  });
}
